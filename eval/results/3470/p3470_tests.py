import pytest
from p3470oracle import Solution


@pytest.mark.parametrize(
    "n, k, expected",
    [
        (1, 1, [1]),
        (2, 1, [1, 2]),
        (2, 2, []),
        (3, 1, [1, 2, 3]),
        (3, 2, [1, 3, 2]),
        (4, 1, [1, 2, 3, 4]),
        (4, 2, [1, 3, 2, 4]),
        (5, 1, [1, 2, 3, 4, 5]),
        (5, 2, [1, 3, 2, 4, 5]),
        (5, 3, [1, 3, 4, 2, 5]),
        (6, 1, [1, 2, 3, 4, 5, 6]),
        (6, 2, [1, 3, 2, 4, 5, 6]),
        (6, 3, [1, 3, 4, 2, 5, 6]),
        (6, 4, [1, 3, 4, 5, 2, 6]),
        (7, 1, [1, 2, 3, 4, 5, 6, 7]),
        (7, 2, [1, 3, 2, 4, 5, 6, 7]),
        (7, 3, [1, 3, 4, 2, 5, 6, 7]),
        (7, 4, [1, 3, 4, 5, 2, 6, 7]),
        (8, 1, [1, 2, 3, 4, 5, 6, 7, 8]),
        (8, 2, [1, 3, 2, 4, 5, 6, 7, 8]),
    ],
)
def test_permute(n, k, expected):
    assert Solution().permute(n, k) == expected
